// Exportable reports. Markdown keeps every category (facts, assumptions, examples, AI, outputs) separate.

import { TYPES, fieldsFor, metricsFor, readiness, runScenario, unitFor, SOURCES } from './scenario.js';

export function scenarioReport(s, fmt, now = Date.now()) {
  const fields = fieldsFor(s);
  const label = (k) => fields.find((f) => f.key === k)?.label || k;
  const lines = [`# ${s.name}`, '', `Type: ${TYPES[s.type].label} · Exported ${new Date(now).toISOString().slice(0, 10)} · Generated by WHAT IF? (offline)`, ''];
  const entries = s.type === 'custom' ? s.model.variables.map((v) => [v.key, { value: v.value, source: v.source || 'fact' }]) : Object.entries(s.inputs);
  lines.push('## Inputs', '', '| Input | Value | Source |', '|---|---|---|');
  for (const [k, e] of entries) lines.push(`| ${label(k)} | ${e.value === null ? '—' : fmt(unitFor(s, k), e.value)} | ${SOURCES[e.source || 'fact']} |`);
  if (s.type === 'custom') {
    lines.push('', '## Formulas', '');
    for (const o of s.model.outputs) lines.push(`- \`${o.key} = ${o.formula}\``);
  }
  const r = readiness(s);
  if (!r.ready) {
    lines.push('', `**Not calculated:** missing ${r.missing.map(label).join(', ') || '—'}; unconfirmed AI values ${r.unconfirmed.map(label).join(', ') || '—'}.`);
    return lines.join('\n');
  }
  let res;
  try { res = runScenario(s); } catch (e) { lines.push('', `**Calculation error:** ${e.message}`); return lines.join('\n'); }
  lines.push('', '## Calculated outputs', '', '| Result | Value |', '|---|---|');
  for (const [k, l] of Object.entries(metricsFor(s))) lines.push(`| ${l} | ${fmt(unitFor(s, k), res.summary[k])} |`);
  lines.push('', '## Calculation steps', '');
  for (const st of res.steps) lines.push(`- **${st.label}**: ${st.formula}${st.values ? ` → ${st.values}` : ''}${st.result === null ? '' : ` = ${fmt(st.unit, st.result)}`}`);
  if (res.warnings.length) { lines.push('', '## Warnings', ''); res.warnings.forEach((w) => lines.push(`- ${w}`)); }
  lines.push('', '## Limitations', '');
  res.limitations.forEach((l) => lines.push(`- ${l}`));
  if (r.examples.length) lines.push(`- Inputs using example values: ${r.examples.map(label).join(', ')}.`);
  if (s.notes) lines.push('', '## Notes', '', s.notes);
  lines.push('', '_These results follow from the inputs and assumptions above. They are not predictions or guarantees._');
  return lines.join('\n');
}

const csvCell = (v) => (typeof v === 'number' ? String(Math.round(v * 100) / 100) : `"${String(v).replace(/"/g, '""')}"`);

export function businessCSV(s) {
  const res = runScenario(s);
  const cols = ['month', 'units', 'revenue', 'variableCosts', 'fixedCosts', 'operatingProfit', 'tax', 'netProfit', 'cashIn', 'cashOut', 'netCashFlow', 'cashBalance'];
  return [['scenario', ...cols].join(','), ...res.months.map((m) => [csvCell(s.name), ...cols.map((c) => csvCell(m[c]))].join(','))].join('\n');
}
